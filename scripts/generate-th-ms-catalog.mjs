import fs from "node:fs/promises";
import path from "node:path";
import ts from "typescript";

const root = process.cwd();
const sourceRoot = path.join(root, "src");
const outputFile = path.join(sourceRoot, "lib", "generated-translations.ts");

const walk = async (dir) => {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(entries.map((entry) => {
    const absolute = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(absolute);
    return /\.(ts|tsx)$/.test(entry.name) ? [absolute] : [];
  }));
  return nested.flat();
};

const literalText = (node) => {
  if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) return node.text;
  return null;
};

const strings = new Set();
for (const file of await walk(sourceRoot)) {
  const sourceText = await fs.readFile(file, "utf8");
  const source = ts.createSourceFile(file, sourceText, ts.ScriptTarget.Latest, true, file.endsWith("x") ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
  const visit = (node) => {
    if (ts.isCallExpression(node) && ts.isIdentifier(node.expression)) {
      if (node.expression.text === "c" || node.expression.text === "clinicText") {
        const value = literalText(node.arguments[0]);
        if (value) strings.add(value);
      }
      if (node.expression.text === "asiaCopy" && node.arguments[1] && ts.isObjectLiteralExpression(node.arguments[1])) {
        const english = node.arguments[1].properties.find((property) =>
          ts.isPropertyAssignment(property) && property.name.getText(source).replace(/["']/g, "") === "en",
        );
        if (english && ts.isPropertyAssignment(english)) {
          const value = literalText(english.initializer);
          if (value) strings.add(value);
        }
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
}

const i18nText = await fs.readFile(path.join(sourceRoot, "lib", "asia-i18n.tsx"), "utf8");
const englishBlock = i18nText.match(/\n  en: \{([\s\S]*?)\n  \},\n  zh:/)?.[1] ?? "";
for (const match of englishBlock.matchAll(/^\s*"[^"]+":\s*"((?:\\.|[^"\\])*)",?$/gm)) {
  strings.add(JSON.parse(`"${match[1]}"`));
}

const delay = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const translate = async (text, target, attempt = 0) => {
  const url = new URL("https://translate.googleapis.com/translate_a/single");
  url.searchParams.set("client", "gtx");
  url.searchParams.set("sl", "en");
  url.searchParams.set("tl", target);
  url.searchParams.set("dt", "t");
  url.searchParams.set("q", text);
  try {
    const response = await fetch(url, { headers: { Accept: "application/json" } });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const data = await response.json();
    const translated = data?.[0]?.map((part) => part?.[0] ?? "").join("").trim();
    if (!translated) throw new Error("Empty translation");
    return translated;
  } catch (error) {
    if (attempt >= 3) throw new Error(`${target}: ${text}: ${error.message}`);
    await delay(500 * (attempt + 1));
    return translate(text, target, attempt + 1);
  }
};

const sourceStrings = [...strings].filter((value) => value.trim().length > 0).sort((a, b) => a.localeCompare(b));
const catalogs = { th: {}, ms: {} };
let cursor = 0;
const workers = Array.from({ length: 6 }, async () => {
  while (cursor < sourceStrings.length) {
    const index = cursor++;
    const source = sourceStrings[index];
    catalogs.th[source] = await translate(source, "th");
    catalogs.ms[source] = await translate(source, "ms");
    if ((index + 1) % 25 === 0) process.stdout.write(`translated ${index + 1}/${sourceStrings.length}\n`);
  }
});
await Promise.all(workers);

const generated = `// Generated by scripts/generate-th-ms-catalog.mjs. Review medical copy with native speakers before publication.\n\nexport const generatedTranslations = ${JSON.stringify(catalogs, null, 2)} as const;\n`;
await fs.writeFile(outputFile, generated);
process.stdout.write(`wrote ${sourceStrings.length} source strings to ${path.relative(root, outputFile)}\n`);
